<?php

namespace App\Http\Middleware;

use Illuminate\Http\Request;
use Inertia\Middleware;

class HandleInertiaRequests extends Middleware
{
    /**
     * The root template that is loaded on the first page visit.
     *
     * @var string
     */
    protected $rootView = 'app';

    /**
     * Determine the current asset version.
     */
    public function version(Request $request): ?string
    {
        return parent::version($request);
    }

    /**
     * Define the props that are shared by default.
     *
     * @return array<string, mixed>
     */
    public function share(Request $request): array
    {
        $user = $request->user();

        return [
            ...parent::share($request),
            'auth' => [
                'user' => $user ? [
                    'id' => $user->id,
                    'name' => $user->name,
                    'email' => $user->email,
                    'roles' => $user->getRoleNames()->values()->all(),
                ] : null,
            ],
            'canViewHrDashboard' => $user?->canViewHrDashboard() ?? false,
            'canApproveLeave' => $user?->canApproveLeave() ?? false,
            'flash' => [
                'success' => fn () => $request->session()->get('success'),
                'error' => fn () => $request->session()->get('error'),
            ],
            'enterprise' => [
                'broadcasting' => config('broadcasting.default'),
                'broadcastingEnabled' => in_array(config('broadcasting.default'), ['reverb', 'pusher'], true),
                'redisEnabled' => (bool) config('enterprise.redis.enabled'),
            ],
        ];
    }
}
